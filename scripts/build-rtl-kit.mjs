// Generates mirrored (RTL) copies of the design kit's stylesheets for the Arabic pages.
// The kit is written with physical left/right; rtlcss flips every one of them (margins, paddings,
// positions, text-align, borders, radii, transforms' translateX). The /ar layout loads
// /assets/rtl/<same path>, so the kit's own files are never edited.
//
//   node scripts/build-rtl-kit.mjs     (run after updating anything in public/assets)
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import rtlcss from 'rtlcss';

const ROOT = new URL('../public/assets/', import.meta.url).pathname;
const FILES = [
  'system.css',
  'ui/cards.css',
  'ui/base.css',
  'motion/motion.css',
  'backgrounds/backgrounds.css',
  'layout/layout.css',
  'icons/icon.css',
  'moments/line-carries-colour/moment.css',
  'moments/letters-assemble/moment.css',
];

for (const rel of FILES) {
  const src = await readFile(join(ROOT, rel), 'utf8');
  const out = rtlcss.process(src);
  const dest = join(ROOT, 'rtl', rel);
  await mkdir(dirname(dest), { recursive: true });
  await writeFile(dest, `/* generated by scripts/build-rtl-kit.mjs from ../${rel}: do not edit */\n${out}`);
  console.log('rtl', rel);
}
